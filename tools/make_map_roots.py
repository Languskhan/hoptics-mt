#!/usr/bin/env python3
"""Write the trust anchors the radio uses for HTTPS map-tile downloads.

tile.openstreetmap.org sits behind Fastly; OSM's DNS CAA records allow Let's Encrypt and
GlobalSign to issue its certificates, and Fastly also runs its own CA (Certainly). The radio
verifies the server against exactly these roots - nothing is downloaded over an unverified link.

Usage: make_map_roots.py <out.h> [cert dir, default /etc/ssl/certs]
The output is committed in patches/device-ui.patch; re-run this only to refresh the roots.
"""
import hashlib
import os
import ssl
import sys

ROOTS = [
    "ISRG_Root_X1",  # Let's Encrypt RSA
    "ISRG_Root_X2",  # Let's Encrypt ECDSA
    "GlobalSign_Root_CA_-_R3",
    "GlobalSign_Root_CA_-_R6",
    "GlobalSign_Root_R46",
    "GlobalSign_Root_E46",
    "GlobalSign_ECC_Root_CA_-_R4",
    "GlobalSign_ECC_Root_CA_-_R5",
    "Certainly_Root_R1",  # Fastly's CA
    "Certainly_Root_E1",
]


def main():
    out = sys.argv[1]
    cert_dir = sys.argv[2] if len(sys.argv) > 2 else "/etc/ssl/certs"
    lines = [
        "#pragma once",
        "// Generated by tools/make_map_roots.py - root CAs trusted for map-tile HTTPS (see that script).",
        "// clang-format off",
        "static const char HOPTICS_MAP_ROOTS[] =",
    ]
    for name in ROOTS:
        with open(os.path.join(cert_dir, name + ".pem")) as f:
            pem = f.read().strip()
        der = ssl.PEM_cert_to_DER_cert(pem)
        fp = hashlib.sha256(der).hexdigest().upper()
        lines.append(f"    // {name}  sha256 {fp}")
        for ln in pem.splitlines():
            lines.append(f'    "{ln}\\n"')
    lines.append("    ;")
    lines.append("// clang-format on")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(ROOTS)} roots")


if __name__ == "__main__":
    main()
