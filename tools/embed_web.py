#!/usr/bin/env python3
"""Embed a page (web/hoptics.html, web/files.html) into a C++ header for the firmware web server.

usage: embed_web.py web/hoptics.html <firmware>/src/mesh/http/HopticsWebPage.h [VARIABLE]
       (VARIABLE defaults to HOPTICS_WEB_PAGE)
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
var = sys.argv[3] if len(sys.argv) > 3 else "HOPTICS_WEB_PAGE"
html = open(src, encoding="utf-8").read()

# light minify: drop leading indentation and blank lines (keeps the JS valid - no line joining)
html = "\n".join(line.strip() for line in html.splitlines() if line.strip())

delim = "HOPTICS_HTML"
if f"){delim}\"" in html:
    sys.exit("raw-string delimiter collides with page content")

with open(dst, "w", encoding="utf-8") as f:
    f.write(f"// generated by tools/embed_web.py from {src} - do not edit\n#pragma once\n")
    f.write(f'static const char {var}[] = R"{delim}(')
    f.write(html)
    f.write(f'){delim}";\n')
print(f"{dst}: {len(html.encode('utf-8'))} bytes")
