#!/usr/bin/env python3
"""
Build the offline city table for the Hoptics MT city locator ("Now in <city>").

Input : a GeoNames dump (cities5000.txt or the .zip), https://download.geonames.org/export/dump/
        GeoNames data is CC BY 4.0 - keep the attribution in README / installer page.
Output: a C++ header with a latitude-sorted table (binary-searchable) and one packed name pool.

usage: build_cities.py cities5000.zip HopticsCities.h [--min-pop 5000]
"""
import argparse
import io
import sys
import zipfile

ap = argparse.ArgumentParser()
ap.add_argument("src")
ap.add_argument("dst")
ap.add_argument("--min-pop", type=int, default=5000)
a = ap.parse_args()

if a.src.endswith(".zip"):
    z = zipfile.ZipFile(a.src)
    name = [n for n in z.namelist() if n.endswith(".txt")][0]
    lines = io.TextIOWrapper(z.open(name), encoding="utf-8")
else:
    lines = open(a.src, encoding="utf-8")


def renderable(s):
    # device fonts cover Latin, Latin-1/Extended-A, Greek, Cyrillic (U+0020..U+052F); fall back to ASCII name otherwise
    return all(0x20 <= ord(c) <= 0x52F for c in s)


rows = []
for line in lines:
    f = line.rstrip("\n").split("\t")
    if len(f) < 15:
        continue
    try:
        pop = int(f[14] or 0)
        lat, lon = float(f[4]), float(f[5])
    except ValueError:
        continue
    if pop < a.min_pop or f[6] != "P":
        continue
    nm = f[1] if renderable(f[1]) else f[2]
    cc, adm1 = f[8], f[10]
    # US / Canada / Australia: "City, ST" with the state/province code; elsewhere "City, CC"
    if cc in ("US", "CA", "AU") and adm1 and adm1.isalpha() and len(adm1) <= 3:
        label = f"{nm}, {adm1}"
    else:
        label = f"{nm}, {cc}"
    label = label.replace("\\", "/").replace('"', "'")
    rows.append((round(lat * 1e4), round(lon * 1e4), label, pop))

if not rows:
    sys.exit("no cities parsed")
rows.sort(key=lambda r: r[0])

pool = bytearray()
offs = []
for lat, lon, label, _ in rows:
    offs.append(len(pool))
    pool += label.encode("utf-8") + b"\0"

with open(a.dst, "w", encoding="utf-8") as o:
    o.write("// generated by tools/build_cities.py from GeoNames (CC BY 4.0) - do not edit\n#pragma once\n#include <stdint.h>\n")
    o.write(f"#define HOPTICS_CITY_COUNT {len(rows)}\n")
    o.write("struct HopticsCity { int32_t lat, lon; uint32_t name; }; // lat/lon in 1e-4 degrees, sorted by lat\n")
    o.write("static const HopticsCity HOPTICS_CITIES[HOPTICS_CITY_COUNT] = {\n")
    for (lat, lon, _, _), off in zip(rows, offs):
        o.write(f"{{{lat},{lon},{off}}},")
    o.write("\n};\n// UTF-8 bytes; unsigned so values >127 are valid initialisers\nstatic const unsigned char HOPTICS_CITY_NAMES_RAW[] = {\n")
    for i in range(0, len(pool), 32):
        o.write(",".join(str(b) for b in pool[i : i + 32]) + ",\n")
    o.write("0};\n#define HOPTICS_CITY_NAMES ((const char *)HOPTICS_CITY_NAMES_RAW)\n")
size = len(rows) * 12 + len(pool)
print(f"{a.dst}: {len(rows)} cities, ~{size // 1024} KB in flash")
