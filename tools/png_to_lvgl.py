#!/usr/bin/env python3
"""Convert PNG boot backgrounds into an LVGL 9 RGB565 header for the Hoptics MT boot screen.

usage: png_to_lvgl.py HopticsBootBg.h a.png [b.png ...]

All images must share one size. The boot screen shows them in rotation, one per boot.
Floyd-Steinberg dithering spreads the 8-bit -> 5/6/5-bit rounding error, so dark gradients stay smooth
instead of banding. Output is little-endian RGB565 (LVGL's native layout), stored as const data in flash.
Needs only Pillow.
"""
import sys

from PIL import Image


def rgb565_dithered(path):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    px = [list(im.getpixel((x, y))) for y in range(h) for x in range(w)]
    err = [[0.0, 0.0, 0.0] for _ in range(w * h)]
    out = bytearray()
    levels = (31, 63, 31)
    for y in range(h):
        for x in range(w):
            i = y * w + x
            q = []
            for c in range(3):
                v = min(255.0, max(0.0, px[i][c] + err[i][c]))
                n = round(v / 255 * levels[c])
                e = v - n * 255 / levels[c]
                q.append(n)
                for dx, dy, f in ((1, 0, 7 / 16), (-1, 1, 3 / 16), (0, 1, 5 / 16), (1, 1, 1 / 16)):
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < w and yy < h:
                        err[yy * w + xx][c] += e * f
            v565 = (q[0] << 11) | (q[1] << 5) | q[2]
            out += bytes((v565 & 0xFF, v565 >> 8))
    return w, h, out


def main():
    dst, srcs = sys.argv[1], sys.argv[2:]
    if not srcs:
        sys.exit("usage: png_to_lvgl.py out.h a.png [b.png ...]")
    imgs = [rgb565_dithered(s) for s in srcs]
    w, h = imgs[0][0], imgs[0][1]
    if any((iw, ih) != (w, h) for iw, ih, _ in imgs):
        sys.exit("all images must be %dx%d" % (w, h))
    with open(dst, "w") as f:
        f.write("// generated by tools/png_to_lvgl.py - do not edit\n#pragma once\n#include <stdint.h>\n")
        f.write("#define HOPTICS_BOOT_BG_W %d\n#define HOPTICS_BOOT_BG_H %d\n#define HOPTICS_BOOT_BG_COUNT %d\n"
                % (w, h, len(imgs)))
        for k, (src, (_, _, data)) in enumerate(zip(srcs, imgs)):
            f.write("// %s\nstatic const uint8_t hoptics_boot_bg_%d[%d] = {\n" % (src.split("/")[-1], k, len(data)))
            for j in range(0, len(data), 24):
                f.write("    " + ",".join("0x%02x" % b for b in data[j:j + 24]) + ",\n")
            f.write("};\n")
        f.write("static const uint8_t *const hoptics_boot_bgs[HOPTICS_BOOT_BG_COUNT] = {%s};\n"
                % ", ".join("hoptics_boot_bg_%d" % k for k in range(len(imgs))))
    print("%s: %d image(s) %dx%d RGB565, %d bytes" % (dst, len(imgs), w, h, sum(len(d) for _, _, d in imgs)))


if __name__ == "__main__":
    main()
